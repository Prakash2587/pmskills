'use strict';
/* Builds a single self-contained HTML file of a wizard tool — no server, no
 * network, works by double-clicking. Run: node build/standalone.js
 *
 * It inlines the same three layers the hosted page loads (tested engine bundle,
 * wizard shell, the skill's steps), so the offline file cannot drift from the
 * deployed one. Run build/bundle.js first if the engine changed. */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

const LIVE_SITE = 'https://pmskills-920403142.development.catalystserverless.com/app/index.html';
const REPO = 'https://github.com/Prakash2587/pmskills';

const TOOLS = [
  { app: 'site/tools/cost-capacity.app.js', title: 'Capacity & Cost Planner — PM Skills', out: 'capacity-cost-planner.html' },
];

// A literal "</script" inside inlined JS would end the tag early.
const safe = js => js.replace(/<\/script/gi, '<\\/script');

for (const tool of TOOLS) {
  // Relative links mean nothing in a file opened from disk — point them at the live site and repo.
  const app = read(tool.app).replace(/\.\.\/index\.html#install/g, `${REPO}#install`);

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${tool.title.replace(/&/g, '&amp;')}</title>
<!-- GENERATED by build/standalone.js — self-contained, works offline. Do not edit; edit the sources. -->
<style>
${read('site/wizard/wizard.css')}
.crumb { max-width: 1180px; margin: 0 auto; padding: 14px 16px 0; font-size: 12px; }
.crumb a { color: var(--muted); }
</style>
</head>
<body>
<div class="crumb"><a href="${LIVE_SITE}" target="_blank" rel="noopener">PM Skills &rarr;</a></div>
<div id="root"></div>
<script>
${safe(read('site/engine.bundle.js'))}
</script>
<script>
${safe(read('site/wizard/wizard.js'))}
</script>
<script>
${safe(app)}
</script>
</body>
</html>
`;

  const dest = path.join(root, 'dist', tool.out);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, html);
  console.log(`wrote dist/${tool.out} (${(html.length / 1024).toFixed(1)} KB, self-contained)`);
}
